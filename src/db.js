// Banco de dados Postgres.
// • Na nuvem (DATABASE_URL definida): Supabase, ou qualquer Postgres, pelo driver "pg".
// • No computador da escola ou em desenvolvimento: PGlite, um Postgres completo que roda dentro do
//   próprio Node e guarda tudo na pasta dados/ — nada para instalar.
const path = require('node:path');
const fs = require('node:fs');

const FUSO = process.env.FUSO_HORARIO || 'America/Belem';
const NA_NUVEM = !!process.env.DATABASE_URL;
const DATA_DIR = process.env.DATA_DIR || path.join(__dirname, '..', 'dados');

// Troca os "?" do SQL por $1, $2… (formato do Postgres)
function converter(sql) {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

let consultar; // (sql, params) => { rows, n }
let executarBruto; // várias instruções de uma vez, sem parâmetros
let transacaoBruta; // (fn(consultarTx)) => resultado

if (NA_NUVEM) {
  const { Pool, types } = require('pg');
  types.setTypeParser(20, (v) => (v == null ? v : Number(v))); // bigint → número
  const url = new URL(process.env.DATABASE_URL);
  url.searchParams.delete('sslmode'); // o SSL é configurado abaixo
  const pool = new Pool({
    connectionString: url.toString(),
    ssl: process.env.DB_SSL === '0' ? false : { rejectUnauthorized: false },
    max: Number(process.env.DB_CONEXOES) || 3,
    idleTimeoutMillis: 10_000,
  });
  consultar = async (sql, params = []) => { const r = await pool.query(converter(sql), params); return { rows: r.rows, n: r.rowCount }; };
  executarBruto = (sql) => pool.query(sql);
  transacaoBruta = async (fn) => {
    const c = await pool.connect();
    try {
      await c.query('BEGIN');
      const r = await fn(async (sql, params = []) => { const x = await c.query(converter(sql), params); return { rows: x.rows, n: x.rowCount }; });
      await c.query('COMMIT');
      return r;
    } catch (e) {
      await c.query('ROLLBACK').catch(() => {});
      throw e;
    } finally {
      c.release();
    }
  };
} else {
  const { PGlite } = require('@electric-sql/pglite');
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const pg = new PGlite(path.join(DATA_DIR, 'banco'));
  consultar = async (sql, params = []) => { const r = await pg.query(converter(sql), params); return { rows: r.rows, n: r.affectedRows ?? 0 }; };
  executarBruto = (sql) => pg.exec(sql);
  transacaoBruta = (fn) => pg.transaction((tx) => fn(async (sql, params = []) => {
    const r = await tx.query(converter(sql), params);
    return { rows: r.rows, n: r.affectedRows ?? 0 };
  }));
}

// Atalhos usados no resto do sistema
function ajudantes(q) {
  return {
    todos: async (sql, ...p) => (await q(sql, p)).rows,
    um: async (sql, ...p) => (await q(sql, p)).rows[0] || null,
    exec: (sql, ...p) => q(sql, p),
  };
}
const db = ajudantes(consultar);
const transacao = (fn) => transacaoBruta((q) => fn(ajudantes(q)));

