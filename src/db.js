let preparando = null;
// Cria as tabelas na primeira vez. Pode ser chamada várias vezes: só roda uma.
function pronto() {
  if (!preparando) {
    preparando = (async () => {
      await executarBruto(ESQUEMA);
      for (const [k, v] of Object.entries(PADROES)) {
        await db.exec('INSERT INTO config (chave, valor) VALUES (?, ?) ON CONFLICT (chave) DO NOTHING', k, v);
      }
    })().catch((e) => { preparando = null; throw e; });
  }
  return preparando;
}

async function getConfig() {
  const out = {};
  for (const r of await db.todos('SELECT chave, valor FROM config')) out[r.chave] = r.valor;
  return out;
}
function setConfig(chave, valor) {
  return db.exec('INSERT INTO config (chave, valor) VALUES (?, ?) ON CONFLICT (chave) DO UPDATE SET valor = excluded.valor',
    chave, valor == null ? '' : String(valor));
}
// "conexao" permite registrar dentro de uma transação (passe o db recebido por transacao())
function registrarAtividade(tipo, descricao, quem = null, conexao = db) {
  return conexao.exec('INSERT INTO atividades (tipo, descricao, usuario) VALUES (?, ?, ?)', tipo, descricao, quem);
}

